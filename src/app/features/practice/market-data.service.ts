/** Candles per replay: the first `HISTORY_BARS` are visible context, the rest are replayed. */
export const REPLAY_BARS = 1000;
export const HISTORY_BARS = 150;

/** One file of `public/market-data/`, as listed in its `index.json`. */
export interface MarketDataFile {
  file: string;
  count: number;
  from: number;
  to: number;
}

export interface MarketDataIndex {
  source: string;
  generatedAt: string;
  instruments: Record<string, Record<string, MarketDataFile[]>>;
}

/** Rows as stored: `[timeSeconds, open, high, low, close]`. */
type Row = [number, number, number, number, number];

// Static files generated by scripts/fetch-market-data.mjs and served with the app.
const BASE = '/market-data';

/** Which files hold candles `[start, start + bars)` of a series, and where to slice them. */
export function filesForWindow(files: MarketDataFile[], start: number, bars: number) {
  const parts: { file: string; from: number; to: number }[] = [];
  let offset = 0;
  for (const f of files) {
    const from = Math.max(start - offset, 0);
    const to = Math.min(start + bars - offset, f.count);
    if (from < to) {
      parts.push({ file: f.file, from, to });
    }
    offset += f.count;
  }
  return parts;
}

/**
 * Loads historical candles for the replay from the static files under `/market-data/`
 * (Dukascopy data, refreshed by the "Market data" GitHub workflow).
 */
@Injectable({ providedIn: 'root' })
export class MarketDataService {
  private index?: Promise<MarketDataIndex>;

  /** A random window of up to `REPLAY_BARS` consecutive candles. */
  async loadRandomWindow(
    symbol: string,
    interval: string,
    random = Math.random,
  ): Promise<Candle[]> {
    const files = (await this.loadIndex()).instruments[symbol]?.[interval] ?? [];
    const total = files.reduce((sum, f) => sum + f.count, 0);
    const bars = Math.min(REPLAY_BARS, total);
    const start = Math.floor(random() * (total - bars + 1));
    const parts = await Promise.all(
      filesForWindow(files, start, bars).map(async (part) =>
        (await this.getJson<Row[]>(part.file)).slice(part.from, part.to),
      ),
    );
    return parts.flat().map(([time, open, high, low, close]) => ({ time, open, high, low, close }));
  }

  private loadIndex(): Promise<MarketDataIndex> {
    this.index ??= this.getJson<MarketDataIndex>('index.json').catch((error) => {
      this.index = undefined;
      throw error;
    });
    return this.index;
  }

  private async getJson<T>(path: string): Promise<T> {
    const response = await fetch(`${BASE}/${path}`);
    if (!response.ok) {
      throw new Error(`HTTP ${response.status} for ${path}`);
    }
    return response.json();
  }
}
